export function preferencesForCategory(
  category: SettingsCategoryId
): PreferenceDefinition[] {
  return PREFERENCE_REGISTRY.filter((item) => item.category === category)
}

export function getPreference(id: string): PreferenceDefinition | undefined {
  return PREFERENCE_REGISTRY.find((item) => item.id === id)
}

export function defaultPreferenceValues(): Record<string, PreferenceValue> {
  const values: Record<string, PreferenceValue> = {}
  for (const item of PREFERENCE_REGISTRY) {
    if (item.kind === "preference") {
      values[item.id] = item.defaultValue
    }
  }
  return values
}
