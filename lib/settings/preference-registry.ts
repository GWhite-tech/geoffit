import type {
  PreferenceDefinition,
  PreferenceValue,
  SettingsCategoryId,
} from "./types"

function pref(
  partial: Omit<PreferenceDefinition, "scope" | "kind" | "keywords"> & {
    keywords?: string[]
    scope?: PreferenceDefinition["scope"]
    kind?: PreferenceDefinition["kind"]
    availability?: PreferenceDefinition["availability"]
  }
): PreferenceDefinition {
  return {
    scope: partial.scope ?? "user",
    kind: partial.kind ?? "preference",
    keywords: partial.keywords ?? [],
    availability: partial.availability ?? "available",
    ...partial,
  }
}

